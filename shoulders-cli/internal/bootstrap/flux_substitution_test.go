// Live defect: flux's kustomize build produced 12 objects where
// `kubectl kustomize` produced 13, silently dropping the Cilium HelmRelease
// from the GitOps set. The only material difference between the two paths is
// Flux's postBuild variable substitution, which is skipped in `flux build
// --dry-run`.
//
// Flux substitutes on the rendered YAML as text (envsubst semantics), not
// node-wise. A value containing YAML-significant characters can therefore
// corrupt the document it lands in — and, if the document is part of a
// multi-document stream, the documents after it.
//
// This test reproduces the whole chain locally: build the profile path the way
// flux does, generate the real platform-config ConfigMap, substitute, and
// re-parse.

var substitutionPattern = regexp.MustCompile(`\$\{([\w.-]+)\}`)

func TestFluxSubstitutionDoesNotDropResources(t *testing.T) {
	repoRoot, err := filepath.Abs(filepath.Join("..", "..", ".."))
	if err != nil {
		t.Fatalf("resolve repo root: %v", err)
	}

	// 1. Build the profile path exactly as flux's kustomize-controller does.
	fs := filesys.MakeFsOnDisk()
	k := krusty.MakeKustomizer(krusty.MakeDefaultOptions())
	res, err := k.Run(fs, filepath.Join(repoRoot, "2-addons/profiles/small/helm-releases"))
	if err != nil {
		t.Fatalf("build profile path: %v", err)
	}
	var before []string
	for _, r := range res.Resources() {
		before = append(before, r.GetKind()+"/"+r.GetName())
	}
	sort.Strings(before)
	t.Logf("built %d resources", len(before))

	// 2. The ConfigMap flux substitutes from, generated by the CLI.
	// Real TLS material: the live ConfigMap carried actual certificates, and
	// their base64 encoding is the largest value in the set.
	publicConfig := PublicDomainConfig{}
	tlsMaterial, err := DefaultDexTLSMaterial()
	if err != nil {
		t.Fatalf("generate dex tls material: %v", err)
	}
	publicConfig.TLS = tlsMaterial

	configMapYAML := fluxPlatformConfigManifest(ProfileSmallForTest, publicConfig)
	var platformConfig struct {
		Data map[string]string `json:"data"`
	}
	if err := yaml.Unmarshal(configMapYAML, &platformConfig); err != nil {
		t.Fatalf("parse platform config: %v", err)
	}
	if len(platformConfig.Data) == 0 {
		t.Fatal("platform config has no data")
	}

	// 3. Substitute, as flux does, on the rendered text.
	rendered, err := res.AsYaml()
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	substituted := substitutionPattern.ReplaceAllStringFunc(string(rendered), func(match string) string {
		key := match[2 : len(match)-1]
		if value, ok := platformConfig.Data[key]; ok {
			return value
		}
		return match
	})

	// 4. Re-parse and compare.
	var after []string
	for _, doc := range splitYAMLDocuments(substituted) {
		var probe struct {
			Kind     string `json:"kind"`
			Metadata struct {
				Name string `json:"name"`
			} `json:"metadata"`
		}
		if err := yaml.Unmarshal([]byte(doc), &probe); err != nil {
			t.Errorf("substituted output is not parseable: %v\n--- document ---\n%s", err, truncateForTest(doc))
			continue
		}
		if probe.Kind == "" {
			continue
		}
		after = append(after, probe.Kind+"/"+probe.Metadata.Name)
	}
	sort.Strings(after)

	if len(after) != len(before) {
		t.Errorf("substitution changed the resource count: %d -> %d\nbefore: %v\nafter:  %v",
			len(before), len(after), before, after)
	}
	if !containsForTest(after, "HelmRelease/cilium") {
		t.Errorf("the Cilium HelmRelease did not survive substitution; resources after it were lost\n%v", after)
	}
}

func splitYAMLDocuments(text string) []string {
	parts := strings.Split(text, "\n---\n")
	out := make([]string, 0, len(parts))
	for _, part := range parts {
		if strings.TrimSpace(part) == "" {
			continue
		}
		out = append(out, part)
	}
	return out
}

func containsForTest(list []string, want string) bool {
	for _, item := range list {
		if item == want {
			return true
		}
	}
	return false
}

func truncateForTest(s string) string {
	if len(s) > 400 {
		return s[:400] + "..."
	}
	return s
}

// ProfileSmallForTest keeps the test independent of the config package's
// profile constants.
const ProfileSmallForTest = "small"

var _ = os.Getenv
